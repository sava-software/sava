  /// The four `V1TransactionConfig` fields as kit was given them (`config`) or read them back
  /// (`read_back_config`): `none` when kit had no config at all, otherwise
  /// `priority_fee:compute_unit_limit:loaded_accounts_data_size_limit:heap_size` with `-` for an
  /// absent field. An absent field and an explicit 0 both read as 0 through Sava's skeleton; only the
  /// mask tells them apart.
  private record Config(boolean present, Long priorityFee, Long computeUnitLimit, Long accountDataSizeLimit, Long heapSize) {

    static Config parse(final String text, final int lineNumber) {
      if (text.equals("none")) {
        return new Config(false, null, null, null, null);
      }
      final String[] fields = text.split(":", -1);
      assertEquals(4, fields.length, () -> "config fields at " + lineNumber);
      return new Config(true, field(fields[0]), field(fields[1]), field(fields[2]), field(fields[3]));
    }

    private static Long field(final String text) {
      return text.equals("-") ? null : Long.valueOf(text);
    }

    long priorityFeeOrZero() {
      return priorityFee == null ? 0L : priorityFee;
    }

    int computeUnitLimitOrZero() {
      return computeUnitLimit == null ? 0 : Math.toIntExact(computeUnitLimit);
    }

    int accountDataSizeLimitOrZero() {
      return accountDataSizeLimit == null ? 0 : Math.toIntExact(accountDataSizeLimit);
    }

    int heapSizeOrZero() {
      return heapSize == null ? 0 : Math.toIntExact(heapSize);
    }

    /// The builder serializes a field only when its value is non-zero, so an explicit 0 is the one
    /// kit input it cannot reproduce.
    boolean hasExplicitZero() {
      final Long zero = 0L;
      return zero.equals(priorityFee) || zero.equals(computeUnitLimit) || zero.equals(accountDataSizeLimit) || zero.equals(heapSize);
    }
  }

  private record Vector(
      String id,
      String configText,
      Config config,
      String extra,
      int configMask,
      int numSigners,
      int numReadonlySigned,
      int numReadonlyUnsigned,
      List<String> staticAccounts,
      List<String> programIds,
      List<byte[]> instructionData,
      byte[] unsignedMessage,
      byte[] signedWire,
      List<byte[]> signatures,
      int readBackVersion,
      Config readBackConfig
  ) {

    boolean builderProducible() {
      return !config.hasExplicitZero();
    }

    List<String> signerAddresses() {
      return staticAccounts.subList(0, numSigners);
    }

    boolean signer(final int accountIndex) {
      return accountIndex < numSigners;
    }

    boolean writable(final int accountIndex) {
      return signer(accountIndex)
          ? accountIndex < numSigners - numReadonlySigned
          : accountIndex < staticAccounts.size() - numReadonlyUnsigned;
    }
  }
