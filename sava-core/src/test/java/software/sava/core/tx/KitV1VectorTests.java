///
/// Two vectors are exceptions the fixture exists to make explicit. `e_explicit_zeros` is a shape
/// [TxBuilder] cannot emit (an explicit 0 clears the mask bit), pinned by
/// [#builderCannotEmitKitsExplicitZeroConfigValues]; `i_two_readonly_programs` puts three accounts in
