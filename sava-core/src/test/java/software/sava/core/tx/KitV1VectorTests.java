/// Builder-side external oracle for Sava's SIMD-0385 transaction v1 support: the committed fixture is
/// generated by `@solana/kit` 8.0.0 — the maintained TypeScript implementation — driven by the locked
/// generator in `src/test/solana/kit-v1-vectors`. Normal Java tests need neither Node nor network
/// access; Gradle only reads the TSV.
///
/// The sibling [V1MessageConformanceTests] fixture is produced by a Rust program Sava's authors wrote
/// against `solana-message`, so a misreading of the SIMD shared between that program and Sava's
/// builder would agree with itself. Kit's compiler, signer, and decoders share no code and no author
/// with either, and every byte in this fixture comes from kit: the unsigned message from
/// `compileTransaction`, the signed wire from `signTransactionMessageWithSigners`, and the read-back
/// columns from kit's own decoders. Sava contributes nothing at generation time.
///
/// Three directions are pinned. Build: [TxBuilder] with the seeded signers reproduces kit's bytes
/// byte-for-byte for every vector it can express. Read: [TransactionSkeleton#deserializeSkeleton]
/// reports what kit says it wrote, including the `TransactionConfigMask` bits an explicit zero keeps.
/// Sign: re-signing kit's zeroed signature block reproduces kit's ed25519 signatures in kit's slots.
/// The fourth direction — kit decoding Sava's bytes — was verified once by the spike's `decode.ts`
