    assertEquals(config.priorityFeeOrZero(), skeleton.priorityFeeLamports(), label + " priority fee");
    assertEquals(config.computeUnitLimitOrZero(), skeleton.computeUnitLimit(), label + " compute unit limit");
    assertEquals(config.accountDataSizeLimitOrZero(), skeleton.accountDataSizeLimit(), label + " account data size limit");
    assertEquals(config.heapSizeOrZero(), skeleton.heapSize(), label + " heap size");
