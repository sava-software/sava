  /// Three read-only non-signer programs sit in one role. Kit orders same-role accounts with an
  /// `Intl.Collator("en")` comparison over their base58 text; Sava's `LEGACY_META_COMPARATOR`
  /// returns 0 for such ties, so their relative order is whatever the account map yields. Neither
  /// order is more correct — SIMD-0385 does not specify one — so byte equality is the wrong
  /// property here. What must hold is canonical equivalence: the same header, the same account set
  /// with the same roles, the same instructions once account indexes are resolved back to keys, the
  /// same signer keys, and a valid signature from each signer over whatever message Sava produced.
  /// Sava's reader resolves both sides; its agreement with kit's own columns is pinned separately by
  /// [#readerParsesKitWireAsKitDescribesIt].
  ///
  /// If the orders coincide, the bytes must coincide too, so a change to either side's ordering
  /// shows up here in one direction or the other rather than silently widening the gap. At the
  /// time of writing they do not coincide: kit compiles `1111…, Ed25519…, Memo…` and Sava's map
  /// yields `Ed25519…, 1111…, Memo…`, so this vector really does exercise the tie-break.
  @Test
  void builderAgreesWithKitUpToSameRoleOrderOnTwoReadonlyPrograms() throws IOException {
    final var vector = vector(loadFixture().vectors(), TIE_BREAK_VECTOR);
    assertEquals(3, vector.numReadonlyUnsigned(), "three read-only programs share a role");
    final var built = build(vector, configuredBuilder(vector));
    final var id = vector.id();

    final var kitSkeleton = TransactionSkeleton.deserializeSkeleton(vector.signedWire());
    final var savaSkeleton = TransactionSkeleton.deserializeSkeleton(built.signedWire());
    assertEquals(1, savaSkeleton.version(), id);
    assertEquals(vector.numSigners(), savaSkeleton.numSignatures(), id + " header signers");
    assertEquals(vector.numReadonlySigned(), savaSkeleton.numReadonlySignedAccounts(), id + " header readonly signed");
    assertEquals(vector.numReadonlyUnsigned(), savaSkeleton.numReadonlyUnsignedAccounts(), id + " header readonly unsigned");
    assertEquals(vector.staticAccounts().size(), savaSkeleton.numAccounts(), id + " account count");
    assertEquals(vector.unsignedMessage().length, built.unsignedMessage().length, id + " message length");
    assertEquals(vector.signedWire().length, built.signedWire().length, id + " wire length");
    assertEquals(vector.configMask(), assertInstanceOf(V1TransactionSkeleton.class, savaSkeleton).configMask(), id + " config mask");

    // Same accounts in the same roles, compared as a set.
    final var savaAccounts = savaSkeleton.parseAccounts();
    final var kitAccounts = kitSkeleton.parseAccounts();
    assertEquals(rolesByAddress(kitAccounts), rolesByAddress(savaAccounts), id + " account roles");
    assertEquals(new TreeSet<>(vector.staticAccounts()), new TreeSet<>(addresses(savaAccounts)), id + " account set");
    assertEquals(
        vector.signerAddresses(),
        Arrays.stream(savaSkeleton.parseSignerPublicKeys()).map(PublicKey::toBase58).toList(),
        id + " signer keys"
    );

    // Same instructions once indexes are resolved back to keys.
    final var kitInstructions = kitSkeleton.parseInstructions(kitAccounts);
    final var savaInstructions = savaSkeleton.parseInstructions(savaAccounts);
    assertEquals(vector.programIds().size(), savaInstructions.length, id + " instruction count");
    for (int index = 0; index < savaInstructions.length; ++index) {
      final var kit = kitInstructions[index];
      final var sava = savaInstructions[index];
      assertEquals(vector.programIds().get(index), sava.programId().publicKey().toBase58(), id + " program " + index);
      assertArrayEquals(vector.instructionData().get(index), sava.copyData(), id + " data " + index);
      assertEquals(addresses(kit.accounts()), addresses(sava.accounts()), id + " instruction " + index + " accounts");
    }

    // A valid signature from each signer over the message Sava actually produced.
    final int messageLength = built.unsignedMessage().length;
    final var signerKeys = savaSkeleton.parseSignerPublicKeys();
    for (int index = 0; index < signerKeys.length; ++index) {
      final byte[] signature = signatureSlot(built.signedWire(), messageLength, index);
      assertTrue(
          PublicKey.verifySignature(signerKeys[index].toByteArray(), 0, built.signedWire(), 0, messageLength, signature),
          id + " signature " + index + " verifies for " + signerKeys[index].toBase58()
      );
    }

    // When the orders coincide nothing else may differ.
    if (addresses(savaAccounts).equals(vector.staticAccounts())) {
      assertSavaBytesEqualKit(vector, built);
    }
  }

  /// The read-side pin, for every vector including the two the builder cannot reproduce. Sava's
  /// skeleton must report what kit says it wrote: version 1, each config value (0 when absent),
  /// the raw `TransactionConfigMask` — which is how an explicit zero is told apart from an absent
  /// field, since both read as 0 — the header counts, the blockhash, every static account in kit's
  /// order, the signer keys, every program id and instruction payload, and the implied boundary
  /// between message and signature block. Kit's read-back columns are its own decoders' view of the
  /// same bytes, and Sava must agree with those too.
  @Test
  void readerParsesKitWireAsKitDescribesIt() throws IOException {
    for (final var vector : loadFixture().vectors()) {
      final var id = vector.id();
      final byte[] wire = vector.signedWire();
      final var skeleton = assertInstanceOf(
          V1TransactionSkeleton.class,
          TransactionSkeleton.deserializeSkeleton(wire),
          id + " dispatches to the v1 skeleton"
      );
      assertEquals(1, skeleton.version(), id);
      assertEquals(vector.readBackVersion(), skeleton.version(), id + " kit read back the same version");
      assertTrue(skeleton.isVersioned(), id);
      assertFalse(skeleton.isLegacy(), id);

      assertEquals(vector.configMask(), skeleton.configMask(), id + " config mask");
      // Kit's decompiler reports a config object exactly when a mask bit is set — an all-zero
      // explicit config (e_explicit_zeros) is still "present", and a zero mask is "none".
      assertEquals(
          vector.readBackConfig().present(),
          skeleton.configMask() != 0,
          id + " kit reports a config object iff the mask is non-zero"
      );
      assertConfigMatches(id + " input", vector.config(), skeleton);
      assertConfigMatches(id + " kit read back", vector.readBackConfig(), skeleton);

      assertEquals(vector.numSigners(), skeleton.numSignatures(), id + " signatures");
      assertEquals(vector.numReadonlySigned(), skeleton.numReadonlySignedAccounts(), id + " readonly signed");
      assertEquals(vector.numReadonlyUnsigned(), skeleton.numReadonlyUnsignedAccounts(), id + " readonly unsigned");
      assertEquals(vector.staticAccounts().size(), skeleton.numAccounts(), id + " accounts");
      assertEquals(0, skeleton.numIndexedAccounts(), id + " no lookup table accounts");
      assertArrayEquals(BLOCKHASH, skeleton.blockHash(), id + " blockhash");
      assertEquals(vector.staticAccounts().getFirst(), skeleton.feePayer().toBase58(), id + " fee payer");

      final var accounts = skeleton.parseAccounts();
      assertEquals(vector.staticAccounts(), addresses(accounts), id + " static accounts in kit's order");
      assertEquals(
          vector.signerAddresses(),
          Arrays.stream(skeleton.parseSignerPublicKeys()).map(PublicKey::toBase58).toList(),
          id + " signer keys"
      );
      for (int index = 0; index < accounts.length; ++index) {
        assertEquals(vector.signer(index), accounts[index].signer(), id + " account " + index + " signer role");
        assertEquals(vector.writable(index), accounts[index].write(), id + " account " + index + " writable role");
      }

      assertEquals(vector.programIds().size(), skeleton.numInstructions(), id + " instruction count");
      final var instructions = skeleton.parseInstructions(accounts);
      assertEquals(vector.programIds().size(), instructions.length, id + " parsed instructions");
      for (int index = 0; index < instructions.length; ++index) {
        assertEquals(vector.programIds().get(index), instructions[index].programId().publicKey().toBase58(), id + " program " + index);
        assertArrayEquals(vector.instructionData().get(index), instructions[index].copyData(), id + " data " + index);
      }

      // The message ends where kit's unsigned message ends, and only the signature block follows.
      final int messageLength = vector.unsignedMessage().length;
      assertEquals(messageLength, V1TransactionSkeleton.messageEnd(wire), id + " message end");
      assertEquals(messageLength, V1TransactionSkeleton.requireSignatureBlockOffset(wire), id + " signature block offset");
      assertEquals(messageLength + (vector.numSigners() * Transaction.SIGNATURE_LENGTH), wire.length, id + " wire length");
      assertArrayEquals(vector.unsignedMessage(), Arrays.copyOf(wire, messageLength), id + " message bytes");
      for (int index = 0; index < vector.numSigners(); ++index) {
        assertArrayEquals(vector.signatures().get(index), signatureSlot(wire, messageLength, index), id + " signature slot " + index);
      }
      assertEquals(Base58.encode(vector.signatures().getFirst()), skeleton.id(), id + " transaction id");
    }
  }

  /// The signer pin, for every vector. Zero kit's signature block, parse the result, promote it to a
  /// mutable [Transaction], and sign with the seeded keys: the wire must come back equal to kit's,
  /// which requires Sava to sign exactly the bytes kit signed (the message including its 0x81
  /// prefix, nothing more) and to place each signature in kit's slot for that signer. Ed25519 is
  /// deterministic, so a single differing signed byte changes all 64 bytes of the signature.
  @Test
  void resigningKitMessageReproducesKitSignatures() throws IOException {
    for (final var vector : loadFixture().vectors()) {
      final var id = vector.id();
      final byte[] wire = vector.signedWire();
      final int messageLength = vector.unsignedMessage().length;
      final byte[] unsigned = wire.clone();
      Arrays.fill(unsigned, messageLength, unsigned.length, (byte) 0);

      final var transaction = TransactionSkeleton.deserializeSkeleton(unsigned).createTransaction();
      assertEquals(1, transaction.version(), id);
      assertEquals(vector.numSigners(), transaction.numSigners(), id + " signers");
      for (final var signer : signers(vector)) {
        transaction.sign(signer);
      }
      final byte[] resigned = transaction.serialized();
      assertSameBytes(id + " re-signed wire", wire, resigned);
      for (int index = 0; index < vector.numSigners(); ++index) {
        assertArrayEquals(
            vector.signatures().get(index),
            signatureSlot(resigned, messageLength, index),
            id + " signature " + index + " for " + vector.signerAddresses().get(index)
        );
      }
      assertEquals(Base58.encode(vector.signatures().getFirst()), transaction.getBase58Id(), id + " transaction id");
    }
  }

  /// `e_explicit_zeros` is the one shape kit can emit that [TxBuilder] cannot: kit keeps a field
  /// whose value is 0 in the mask and writes its zero ConfigValue, while the builder treats 0 as
  /// "clear this field" and drops the bit. Both are valid SIMD-0385 encodings and the runtime reads
  /// them identically, so the divergence is deliberate — but it must stay visible. This pins each
  /// half: kit's bytes carry mask `0b1111` over sixteen zero bytes and Sava reads them as such; a
  /// builder given the same zeros emits mask 0 and a message sixteen bytes shorter, and its in-place
  /// setters refuse the absent slots; and kit's explicit-zero shape, once parsed, is exactly the
  /// update-in-place shape whose slots the setters can fill. If the builder ever learns to emit
  /// explicit zeros, [#builderReproducesKitBytesForEveryProducibleVector] should take this vector
  /// over and this test should be retired with it.
  @Test
  void builderCannotEmitKitsExplicitZeroConfigValues() throws IOException {
    final var vector = vector(loadFixture().vectors(), EXPLICIT_ZEROS_VECTOR);
    assertEquals("0:0:0:-", vector.configText(), "kit was asked for explicit zeros and no heap");
    assertFalse(vector.builderProducible(), "the builder byte test skips this vector");
    final int explicitZeroMask = PRIORITY_FEE_MASK | COMPUTE_UNIT_LIMIT_MASK | ACCOUNT_DATA_SIZE_LIMIT_MASK;
    assertEquals(explicitZeroMask, vector.configMask(), "kit keeps the mask bits of explicit zeros");
    assertEquals(0, vector.configMask() & HEAP_SIZE_MASK, "the unset heap has no bit");

    // Kit's bytes: three set fields, all zero, occupying 8 + 4 + 4 bytes after the accounts.
    final byte[] wire = vector.signedWire();
    final var kitSkeleton = assertInstanceOf(V1TransactionSkeleton.class, TransactionSkeleton.deserializeSkeleton(wire));
    assertEquals(explicitZeroMask, kitSkeleton.configMask());
    assertEquals(0L, kitSkeleton.priorityFeeLamports());
    assertEquals(0, kitSkeleton.computeUnitLimit());
    assertEquals(0, kitSkeleton.accountDataSizeLimit());
    assertEquals(0, kitSkeleton.heapSize());
    final int configValuesOffset = V1TransactionSkeleton.V1_ACCOUNTS_OFFSET
        + (vector.staticAccounts().size() * PublicKey.PUBLIC_KEY_LENGTH);
    final int configValuesLength = Integer.bitCount(explicitZeroMask) << 2;
    assertEquals(16, configValuesLength);
    assertEquals(configValuesOffset + configValuesLength, kitSkeleton.instructionsOffset(), "instructions follow the zero ConfigValues");
    for (int offset = configValuesOffset; offset < configValuesOffset + configValuesLength; ++offset) {
      assertEquals(0, wire[offset], "explicit zero ConfigValue byte at " + offset);
    }

    // The builder: the same zeros clear every bit, and the message loses those sixteen bytes.
    final var builder = TxBuilder.createBuilder()
        .feePayer(PAYER.publicKey())
        .addInstructions(instructions(vector))
        .priorityFeeLamports(0L)
        .computeUnitLimit(0)
        .accountDataSizeLimit(0);
    final var built = builder.createTransaction();
    built.setRecentBlockHash(BLOCKHASH);
    final var savaSkeleton = assertInstanceOf(V1TransactionSkeleton.class, TransactionSkeleton.deserializeSkeleton(built.serialized()));
    assertEquals(0, savaSkeleton.configMask(), "an explicit 0 clears the builder's mask bit");
    assertEquals(0, savaSkeleton.configMask() & PRIORITY_FEE_MASK);
    assertEquals(0, savaSkeleton.configMask() & COMPUTE_UNIT_LIMIT_MASK);
    assertEquals(0, savaSkeleton.configMask() & ACCOUNT_DATA_SIZE_LIMIT_MASK);
    assertEquals(
        vector.unsignedMessage().length - configValuesLength,
        built.serialized().length - (vector.numSigners() * Transaction.SIGNATURE_LENGTH),
        "the builder's message is exactly the zero ConfigValues shorter"
    );
    assertThrows(IllegalStateException.class, () -> built.setPriorityFeeLamports(1L), "no priority fee slot to update");
    assertThrows(IllegalStateException.class, () -> built.setComputeUnitLimit(1), "no compute unit limit slot to update");
    assertThrows(IllegalStateException.class, () -> built.setAccountDataSizeLimit(1), "no data size slot to update");

    // Kit's shape, parsed by Sava, is the update-in-place shape the builder reserves with non-zero
    // defaults: every slot is present and the setters fill it without changing the mask or length.
    final byte[] unsigned = wire.clone();
    Arrays.fill(unsigned, vector.unsignedMessage().length, unsigned.length, (byte) 0);
    final var reserved = TransactionSkeleton.deserializeSkeleton(unsigned).createTransaction();
    reserved.setPriorityFeeLamports(5_000L);
    reserved.setComputeUnitLimit(20_000);
    reserved.setAccountDataSizeLimit(65_536);
    assertThrows(IllegalStateException.class, () -> reserved.setHeapSize(64 * 1_024), "the heap slot kit left absent stays absent");
    final var updated = assertInstanceOf(V1TransactionSkeleton.class, TransactionSkeleton.deserializeSkeleton(reserved.serialized()));
    assertEquals(explicitZeroMask, updated.configMask(), "in-place updates keep kit's mask");
    assertEquals(wire.length, reserved.serialized().length, "in-place updates keep kit's length");
    assertEquals(5_000L, updated.priorityFeeLamports());
    assertEquals(20_000, updated.computeUnitLimit());
    assertEquals(65_536, updated.accountDataSizeLimit());
    assertEquals(0, updated.heapSize());
  }

  private static TxBuilder configuredBuilder(final Vector vector) {
    final var config = vector.config();
    final var builder = TxBuilder.createBuilder()
        .feePayer(PAYER.publicKey())
        // 0 clears the builder's default for these two; an absent kit field is an absent slot.
        .computeUnitLimit(config.computeUnitLimitOrZero())
        .accountDataSizeLimit(config.accountDataSizeLimitOrZero());
    if (config.priorityFee() != null) {
      builder.priorityFeeLamports(config.priorityFee());
    }
    if (config.heapSize() != null) {
      builder.heapSize(config.heapSizeOrZero());
    }
    return builder;
  }

  /// Adds the vector's instructions to the builder, stamps the fixed blockhash, captures the message
  /// with an all-zero signature block, then signs with the vector's seeded signers.
  private static Built build(final Vector vector, final TxBuilder builder) {
    final var transaction = builder.addInstructions(instructions(vector)).createTransaction();
    transaction.setRecentBlockHash(BLOCKHASH);
    final byte[] unsigned = transaction.serialized().clone();
    final int messageLength = unsigned.length - (transaction.numSigners() * Transaction.SIGNATURE_LENGTH);
    for (int offset = messageLength; offset < unsigned.length; ++offset) {
      assertEquals(0, unsigned[offset], vector.id() + " unsigned signature block byte at " + offset);
    }
    for (final var signer : signers(vector)) {
      transaction.sign(signer);
    }
    return new Built(transaction, Arrays.copyOf(unsigned, messageLength), transaction.serialized());
  }

  private static void assertSavaBytesEqualKit(final Vector vector, final Built built) {
    final var id = vector.id();
    final var transaction = built.transaction();
    assertEquals(1, transaction.version(), id + " version");
    assertEquals(vector.numSigners(), transaction.numSigners(), id + " signers");
    assertSameBytes(id + " unsigned message", vector.unsignedMessage(), built.unsignedMessage());
    assertSameBytes(id + " signed wire", vector.signedWire(), built.signedWire());
    assertEquals(vector.signedWire().length, transaction.size(), id + " size");
    assertEquals(Base64.getEncoder().encodeToString(vector.signedWire()), transaction.base64EncodeToString(), id + " base64");
    assertEquals(Base58.encode(vector.signatures().getFirst()), transaction.getBase58Id(), id + " transaction id");
  }

  /// Fails with the first differing offset and up to 32 bytes of context from each side.
  private static void assertSameBytes(final String label, final byte[] kit, final byte[] sava) {
    final int diff = Arrays.mismatch(kit, sava);
    if (diff < 0) {
      return;
    }
    fail(String.format(
        "%s: first differing offset=%d (kit len=%d, sava len=%d)%n  kit [%d..+%d]=%s%n  sava[%d..+%d]=%s",
        label, diff, kit.length, sava.length,
        diff, MISMATCH_CONTEXT, context(kit, diff),
        diff, MISMATCH_CONTEXT, context(sava, diff)
    ));
  }

  private static String context(final byte[] bytes, final int from) {
    if (from >= bytes.length) {
      return "<end>";
    }
    return HEX.formatHex(bytes, from, Math.min(bytes.length, from + MISMATCH_CONTEXT));
  }

  private static byte[] signatureSlot(final byte[] wire, final int messageLength, final int index) {
    final int from = messageLength + (index * Transaction.SIGNATURE_LENGTH);
    return Arrays.copyOfRange(wire, from, from + Transaction.SIGNATURE_LENGTH);
  }

