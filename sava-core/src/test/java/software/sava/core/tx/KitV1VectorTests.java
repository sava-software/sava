  private static Fixture loadFixture() throws IOException {
    final var input = KitV1VectorTests.class.getResourceAsStream(RESOURCE);
    assertNotNull(input, "missing fixture " + RESOURCE);
    final var metadata = new LinkedHashMap<String, String>();
    final var vectors = new ArrayList<Vector>();
    boolean sawColumns = false;
    try (var reader = new BufferedReader(new InputStreamReader(input, StandardCharsets.UTF_8))) {
      String line;
      int lineNumber = 0;
      while ((line = reader.readLine()) != null) {
        ++lineNumber;
        final int currentLine = lineNumber;
        assertFalse(line.isBlank(), () -> "blank fixture line " + currentLine);
        if (line.startsWith("# ")) {
          assertFalse(sawColumns, () -> "metadata after columns at " + currentLine);
          final int separator = line.indexOf(": ", 2);
          assertTrue(separator > 2, () -> "malformed metadata at " + currentLine);
          final String key = line.substring(2, separator);
          assertNull(metadata.putIfAbsent(key, line.substring(separator + 2)), () -> "duplicate " + key);
        } else if (!sawColumns) {
          assertEquals(COLUMNS, line, () -> "columns at " + currentLine);
          sawColumns = true;
        } else {
          vectors.add(parseVector(line, currentLine));
        }
      }
    }
    assertTrue(sawColumns, "missing columns");
    assertEquals(EXPECTED_METADATA, metadata, "fixture provenance changed");
    assertEquals(EXPECTED_IDS, vectors.stream().map(Vector::id).toList(), "vector inventory");
    return new Fixture(metadata, vectors);
  }

  private static Vector parseVector(final String line, final int lineNumber) {
    final String[] fields = line.split("\\t", -1);
    assertEquals(13, fields.length, () -> "field count at " + lineNumber);
    final String[] header = fields[4].split(":", -1);
    assertEquals(3, header.length, () -> "header at " + lineNumber);
    final var vector = new Vector(
        fields[0],
        fields[1],
        Config.parse(fields[1], lineNumber),
        fields[2],
        Integer.parseInt(fields[3]),
        Integer.parseInt(header[0]),
        Integer.parseInt(header[1]),
        Integer.parseInt(header[2]),
        List.of(fields[5].split(",", -1)),
        List.of(fields[6].split(",", -1)),
        parseByteArrays(fields[7]),
        HEX.parseHex(fields[8]),
        HEX.parseHex(fields[9]),
        parseByteArrays(fields[10]),
        Integer.parseInt(fields[11]),
        Config.parse(fields[12], lineNumber)
    );
    assertEquals(vector.programIds().size(), vector.instructionData().size(), () -> "instruction columns at " + lineNumber);
    assertEquals(vector.numSigners(), vector.signatures().size(), () -> "signature count at " + lineNumber);
    assertTrue(vector.numSigners() <= vector.staticAccounts().size(), () -> "signer count at " + lineNumber);
    return vector;
  }

  private static List<byte[]> parseByteArrays(final String encoded) {
    if (encoded.isEmpty()) {
      return List.of();
    }
    return Arrays.stream(encoded.split(",", -1)).map(HEX::parseHex).toList();
  }

