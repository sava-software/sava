  private static void assertSameLegacyMeaning(
      final TransactionSkeleton expected,
      final TransactionSkeleton actual,
      final String id
  ) {
    assertTrue(actual.isLegacy(), id);
    assertEquals(expected.numSigners(), actual.numSigners(), id + " required signatures");
    assertEquals(expected.numReadonlySignedAccounts(), actual.numReadonlySignedAccounts(), id);
    assertEquals(expected.numReadonlyUnsignedAccounts(), actual.numReadonlyUnsignedAccounts(), id);
    assertEquals(expected.numIncludedAccounts(), actual.numIncludedAccounts(), id);
    assertArrayEquals(expected.blockHash(), actual.blockHash(), id + " blockhash");
    assertEquals(accountRoles(expected.parseAccounts()), accountRoles(actual.parseAccounts()), id);
    assertEquals(expected.serializedInstructionsLength(), actual.serializedInstructionsLength(), id);
    assertArrayEquals(expected.parseProgramAccounts(), actual.parseProgramAccounts(), id);

    final var expectedInstructions = expected.parseLegacyInstructions();
    final var actualInstructions = actual.parseLegacyInstructions();
    assertEquals(expectedInstructions.length, actualInstructions.length, id);
    for (int index = 0; index < expectedInstructions.length; ++index) {
      final var expectedInstruction = expectedInstructions[index];
      final var actualInstruction = actualInstructions[index];
      assertEquals(expectedInstruction.programId().publicKey(), actualInstruction.programId().publicKey(), id);
      assertEquals(expectedInstruction.accounts(), actualInstruction.accounts(), id + " accounts " + index);
      assertArrayEquals(expectedInstruction.copyData(), actualInstruction.copyData(), id + " data " + index);

      final var expectedWithoutAccounts = expected.parseInstructionsWithoutAccounts()[index];
      final var actualWithoutAccounts = actual.parseInstructionsWithoutAccounts()[index];
      assertEquals(expectedWithoutAccounts.programId(), actualWithoutAccounts.programId(), id);
      assertArrayEquals(expectedWithoutAccounts.copyData(), actualWithoutAccounts.copyData(), id);

      final var discriminator = expectedInstruction.wrapDiscriminator(1);
      final var filtered = actual.filterInstructions(actual.parseAccounts(), discriminator);
      final var filteredWithoutAccounts = actual.filterInstructionsWithoutAccounts(discriminator);
      assertEquals(expectedInstruction.programId(), filtered[0].programId(), id);
      assertEquals(expectedInstruction.programId().publicKey(), filteredWithoutAccounts[0].programId().publicKey(), id);
    }
  }

  private static Map<PublicKey, Role> accountRoles(final AccountMeta[] accounts) {
    final var roles = new HashMap<PublicKey, Role>(accounts.length);
    for (final var account : accounts) {
      assertNull(roles.put(
          account.publicKey(),
          new Role(account.feePayer(), account.signer(), account.write())
      ), () -> "duplicate compiled account " + account.publicKey());
    }
    return roles;
  }

  private static TransactionSkeleton skeletonForMessage(final byte[] message) {
    final int numSignatures = (message[0] & 0x80) == 0
        ? Byte.toUnsignedInt(message[0])
        : Byte.toUnsignedInt(message[1]);
    final byte[] transaction = new byte[
        CompactU16Encoding.getByteLen(numSignatures)
            + (numSignatures * Transaction.SIGNATURE_LENGTH)
            + message.length
        ];
    int offset = CompactU16Encoding.encodeLength(transaction, 0, numSignatures);
    offset += numSignatures * Transaction.SIGNATURE_LENGTH;
    System.arraycopy(message, 0, transaction, offset, message.length);
    return TransactionSkeleton.deserializeSkeleton(transaction);
  }

  private static Transaction canonicalTransaction(
      final Vector vector,
      final TransactionSkeleton rustSkeleton
  ) {
    if (vector.versioned()) {
      return canonicalVersionedTransaction(vector, rustSkeleton, false);
    }
    return Transaction.createTx(
        vector.instructions().stream().map(IxSpec::toInstruction).toList(),
        rustSkeleton.parseAccounts()
    );
  }

  private static Transaction canonicalVersionedTransaction(
      final Vector vector,
      final TransactionSkeleton rustSkeleton,
      final boolean multipleTables
  ) {
    final var instructions = vector.instructions().stream().map(IxSpec::toInstruction).toList();
    final int serializedLength = instructions.stream().mapToInt(Instruction::serializedLength).sum();
    return createVersioned(
        instructions,
        serializedLength,
        rustSkeleton.parseAccounts(),
        emptyLookupTable(0x7200),
        emptyLookupTable(0x7201),
        multipleTables
    );
  }

  private static Transaction createVersioned(
      final List<Instruction> instructions,
      final int serializedLength,
      final AccountMeta[] sortedAccounts,
      final AddressLookupTable firstTable,
      final AddressLookupTable secondTable,
      final boolean multipleTables
  ) {
    return multipleTables
        ? Transaction.createTx(
            instructions,
            serializedLength,
            sortedAccounts.clone(),
            new LookupTableAccountMeta[]{
                LookupTableAccountMeta.createMeta(firstTable),
                LookupTableAccountMeta.createMeta(secondTable)
            }
        )
        : Transaction.createTx(
            instructions,
            serializedLength,
            sortedAccounts.clone(),
            firstTable
        );
  }

  private static AddressLookupTable emptyLookupTable(final int address) {
    final byte[] data = new byte[AddressLookupTable.LOOKUP_TABLE_META_SIZE];
    ByteUtil.putInt32LE(data, AddressLookupTable.DISCRIMINATOR_OFFSET, 1);
    ByteUtil.putInt64LE(data, AddressLookupTable.DEACTIVATION_SLOT_OFFSET, -1L);
    return AddressLookupTable.read(key(address), data);
  }

  private static Map<PublicKey, AccountMeta> merge(
      final AccountMeta feePayer,
      final Instruction instruction
  ) {
    final var accounts = new HashMap<PublicKey, AccountMeta>();
    TransactionRecord.mergeAccounts(feePayer, accounts, List.of(instruction));
    return accounts;
  }

  private static byte[] messageBytes(final Transaction transaction) {
    final var record = (TransactionRecord) transaction;
    return Arrays.copyOfRange(record.serialized(), record.messageOffset(), record.serialized().length);
  }

  private static byte[] versionedWithoutLookups(final Transaction transaction) {
    final var record = (TransactionRecord) transaction;
    final byte[] legacy = record.serialized();
    final byte[] versioned = new byte[legacy.length + 2];
    System.arraycopy(legacy, 0, versioned, 0, record.messageOffset());
    versioned[record.messageOffset()] = (byte) 0x80;
    System.arraycopy(
        legacy,
        record.messageOffset(),
        versioned,
        record.messageOffset() + 1,
        legacy.length - record.messageOffset()
    );
    // One extra byte beyond the version prefix is the compact-u16 zero lookup-table count.
    versioned[versioned.length - 1] = 0;
    return versioned;
  }

  private static List<AccountMeta> metas(
      final int count,
      final boolean signer,
      final boolean writable,
      final int keyBase
  ) {
    final var metas = new ArrayList<AccountMeta>(count);
    for (int index = 0; index < count; ++index) {
      metas.add(AccountMeta.createMeta(key(keyBase + index), writable, signer));
    }
    return metas;
  }

  private static PublicKey key(final int value) {
    final byte[] bytes = new byte[PublicKey.PUBLIC_KEY_LENGTH];
    bytes[0] = (byte) (value >>> 8);
    bytes[1] = (byte) value;
    bytes[31] = 0x5a;
    return PublicKey.createPubKey(bytes);
  }

  private static Fixture loadFixture() throws IOException {
    final var input = LegacyMessageConformanceTests.class.getResourceAsStream(RESOURCE);
    assertNotNull(input, "missing fixture " + RESOURCE);
    final var metadata = new LinkedHashMap<String, String>();
    final var vectors = new ArrayList<Vector>();
    boolean sawColumns = false;
    try (var reader = new BufferedReader(new InputStreamReader(input, StandardCharsets.UTF_8))) {
      String line;
      int lineNumber = 0;
      while ((line = reader.readLine()) != null) {
        ++lineNumber;
        final int currentLine = lineNumber;
        assertFalse(line.isBlank(), () -> "blank fixture line " + currentLine);
        if (line.startsWith("# ")) {
          assertFalse(sawColumns, () -> "metadata after columns at " + currentLine);
          final int separator = line.indexOf(": ", 2);
          assertTrue(separator > 2, () -> "malformed metadata at " + currentLine);
          final String key = line.substring(2, separator);
          assertNull(metadata.putIfAbsent(key, line.substring(separator + 2)), () -> "duplicate " + key);
        } else if (!sawColumns) {
          assertEquals(COLUMNS, line, () -> "columns at " + currentLine);
          sawColumns = true;
        } else {
          vectors.add(parseVector(line, currentLine));
        }
      }
    }
    assertTrue(sawColumns, "missing columns");
    assertEquals(EXPECTED_METADATA, metadata, "fixture provenance changed");
    assertEquals(11, vectors.size());
    return new Fixture(metadata, vectors);
  }

  private static Vector parseVector(final String line, final int lineNumber) {
    final String[] fields = line.split("\\t", -1);
    assertEquals(10, fields.length, () -> "field count at " + lineNumber);
    return new Vector(
        fields[0],
        PublicKey.createPubKey(HEX.parseHex(fields[1])),
        HEX.parseHex(fields[2]),
        parseInstructions(fields[3]),
        HEX.parseHex(fields[4]),
        parseByteArrays(fields[5]),
        parseByteArrays(fields[6]),
        HEX.parseHex(fields[7]),
        parseBoolean(fields[8], lineNumber),
        parseMessageVersion(fields[9], lineNumber)
    );
  }

  private static boolean parseMessageVersion(final String value, final int lineNumber) {
    assertTrue(value.equals("legacy") || value.equals("v0"), () -> "message version at " + lineNumber);
    return value.equals("v0");
  }

  private static List<IxSpec> parseInstructions(final String encoded) {
    final var instructions = new ArrayList<IxSpec>();
    for (final var encodedInstruction : encoded.split(";", -1)) {
      final String[] fields = encodedInstruction.split("\\|", -1);
      assertEquals(3, fields.length, () -> "instruction fields in " + encodedInstruction);
      final var accounts = new ArrayList<MetaSpec>();
      if (!fields[1].isEmpty()) {
        for (final var encodedMeta : fields[1].split(",", -1)) {
          final String[] meta = encodedMeta.split(":", -1);
          assertEquals(3, meta.length, () -> "meta fields in " + encodedMeta);
          accounts.add(new MetaSpec(
              PublicKey.createPubKey(HEX.parseHex(meta[0])),
              meta[1].equals("1"),
              meta[2].equals("1")
          ));
        }
      }
      instructions.add(new IxSpec(
          PublicKey.createPubKey(HEX.parseHex(fields[0])),
          accounts,
          HEX.parseHex(fields[2])
      ));
    }
    return instructions;
  }

  private static List<byte[]> parseByteArrays(final String encoded) {
    if (encoded.isEmpty()) {
      return List.of();
    }
    return Arrays.stream(encoded.split(",", -1)).map(HEX::parseHex).toList();
  }

  private static boolean parseBoolean(final String value, final int lineNumber) {
    assertTrue(value.equals("true") || value.equals("false"), () -> "boolean at " + lineNumber);
    return Boolean.parseBoolean(value);
  }

  private static void assertFileSha256(
      final Map<String, String> metadata,
      final String metadataKey,
      final String relativePath
  ) throws IOException {
    final var path = generatorPath(relativePath);
    assertEquals(
        metadata.get(metadataKey),
        HEX.formatHex(sha256().digest(Files.readAllBytes(path))),
        () -> "stale fixture provenance for " + path
    );
  }

  private static Path generatorPath(final String relativePath) {
    final var moduleRelative = Path.of("src/test/solana/legacy-message-vectors").resolve(relativePath);
    if (Files.isRegularFile(moduleRelative)) {
      return moduleRelative;
    }
    final var repositoryRelative = Path.of("sava-core").resolve(moduleRelative);
    assertTrue(Files.isRegularFile(repositoryRelative), () -> "missing generator input " + relativePath);
    return repositoryRelative;
  }

  private static MessageDigest sha256() {
    try {
      return MessageDigest.getInstance("SHA-256");
    } catch (final NoSuchAlgorithmException e) {
      throw new AssertionError("JDK has no SHA-256 provider", e);
    }
  }

