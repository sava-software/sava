  @Test
  void legacyCompilationMatchesPinnedSolanaMessageSemanticsAndCanonicalBytes() throws IOException {
    final var fixture = loadFixture();
    for (final var vector : fixture.vectors()) {
      if (vector.versioned()) {
        continue;
      }
      final var instructions = vector.instructions().stream().map(IxSpec::toInstruction).toList();
      if (!vector.rustWireRoundTrip()) {
        // Transaction construction is intentionally permissive. These bytes are useful for
        // analysis even though current Solana transaction decoding rejects the outer framing.
        final var transaction = assertDoesNotThrow(
            () -> Transaction.createTx(vector.feePayer(), instructions),
            vector.id()
        );
        assertEquals((byte) 0x80, transaction.serialized()[0], vector.id());
        assertEquals((byte) 0x80, messageBytes(transaction)[0], vector.id());
        continue;
      }
      final var rustSkeleton = skeletonForMessage(vector.message());

      // Sava has always left tied account keys in HashMap encounter order. Rust uses BTreeMap
      // byte ordering and Kit uses its address comparator, so changing that published order
      // would change otherwise valid transaction IDs. Compare the public builder semantically.
      final var publicBuilder = Transaction.createTx(vector.feePayer(), instructions);
      publicBuilder.setRecentBlockHash(vector.blockhash());
      assertSameLegacyMeaning(rustSkeleton, TransactionSkeleton.deserializeSkeleton(publicBuilder.serialized()), vector.id());

      // The overload accepting already ordered accounts has no tie-break choice. Feeding it the
      // Rust message order gives a direct byte-for-byte serializer/index/shortvec oracle.
      final var canonical = Transaction.createTx(instructions, rustSkeleton.parseAccounts());
      canonical.setRecentBlockHash(vector.blockhash());
      assertArrayEquals(vector.message(), messageBytes(canonical), vector.id());

      if (vector.id().equals("max_account_index_255")) {
        final var versionedWithoutLookups = versionedWithoutLookups(canonical);
        final var versionedSkeleton = TransactionSkeleton.deserializeSkeleton(versionedWithoutLookups);
        assertTrue(versionedSkeleton.isVersioned());
        assertEquals(0, versionedSkeleton.lookupTableAccounts().length);
        assertEquals(
            instructions.getFirst().programId().publicKey(),
            versionedSkeleton.parseProgramAccounts()[0],
            "v0 without lookups must also read program index 255 as raw u8"
        );
      }
    }
  }

  @Test
  void collectionSigningMatchesPinnedSolanaSignerSlotsAndEd25519Bytes() throws IOException {
    for (final var vector : loadFixture().vectors()) {
      if (vector.signerSeeds().isEmpty() || !vector.rustWireRoundTrip()) {
        continue;
      }
      final var rustSkeleton = skeletonForMessage(vector.message());
      final var instructions = vector.instructions().stream().map(IxSpec::toInstruction).toList();
      final var transaction = canonicalTransaction(vector, rustSkeleton);
      transaction.setRecentBlockHash(vector.blockhash());
      final List<Signer> signers = vector.signerSeeds().stream()
          .map(Signer::createFromPrivateKey)
          .toList();

      // A List normally selects the published positional overload. The Collection cast selects
      // the existing by-key contract that mirrors VersionedTransaction::try_new.
      transaction.sign((Collection<Signer>) signers);

      final byte[] serialized = transaction.serialized();
      final int signatureOffset = CompactU16Encoding.getByteLen(serialized, 0);
      assertArrayEquals(
          vector.rustSignaturePrefix(),
          Arrays.copyOf(serialized, signatureOffset),
          vector.id() + " signature count prefix"
      );
      assertEquals(vector.rustSignatures().size(), CompactU16Encoding.decode(serialized, 0), vector.id());
      assertEquals(signatureOffset + (vector.rustSignatures().size() * Transaction.SIGNATURE_LENGTH),
          ((TransactionRecord) transaction).messageOffset(), vector.id());
      for (int index = 0; index < vector.rustSignatures().size(); ++index) {
        assertArrayEquals(
            vector.rustSignatures().get(index),
            Arrays.copyOfRange(
                serialized,
                signatureOffset + (index * Transaction.SIGNATURE_LENGTH),
                signatureOffset + ((index + 1) * Transaction.SIGNATURE_LENGTH)
            ),
            vector.id() + " signature slot " + index
        );
      }
      assertArrayEquals(vector.rustSignatures().getFirst(), transaction.getId(), vector.id());
      assertEquals(Base58.encode(vector.rustSignatures().getFirst()), transaction.getBase58Id(), vector.id());
      assertEquals(transaction.getBase58Id(), TransactionSkeleton.deserializeSkeleton(serialized).id(), vector.id());
    }
  }

  @Test
  void v0WithoutLookupsRecordsTheSignatureBoundaryWithoutBlockingConstruction() throws IOException {
    final var vectors = loadFixture().vectors();
    final var accepted = vectors.stream()
        .filter(candidate -> candidate.id().equals("v0_signature_shortvec_127"))
        .findFirst()
        .orElseThrow();
    final var rejected = vectors.stream()
        .filter(candidate -> candidate.id().equals("v0_signature_shortvec_128"))
        .findFirst()
        .orElseThrow();
    assertTrue(accepted.versioned());
    assertTrue(accepted.rustWireRoundTrip());
    assertArrayEquals(new byte[]{0x7f}, accepted.rustSignaturePrefix());
    assertTrue(rejected.versioned());
    assertFalse(rejected.rustWireRoundTrip());
    assertArrayEquals(new byte[]{(byte) 0x80, 0x01}, rejected.rustSignaturePrefix());

    final var rustSkeleton = skeletonForMessage(accepted.message());
    assertTrue(rustSkeleton.isVersioned());
    assertEquals(0, rustSkeleton.version());
    assertEquals(127, rustSkeleton.numSignatures());
    assertEquals(0, rustSkeleton.lookupTableAccounts().length);

    final var singleTablePath = canonicalVersionedTransaction(accepted, rustSkeleton, false);
    final var multipleTablePath = canonicalVersionedTransaction(accepted, rustSkeleton, true);
    for (final var transaction : List.of(singleTablePath, multipleTablePath)) {
      transaction.setRecentBlockHash(accepted.blockhash());
      assertArrayEquals(accepted.message(), messageBytes(transaction));
      assertArrayEquals(
          accepted.rustSignaturePrefix(),
          Arrays.copyOf(transaction.serialized(), accepted.rustSignaturePrefix().length)
      );
      final var parsed = TransactionSkeleton.deserializeSkeleton(transaction.serialized());
      assertEquals(127, parsed.numSignatures());
      assertEquals(0, parsed.lookupTableAccounts().length);

      final byte[] changedBlockhash = key(0x4a4a).toByteArray();
      Transaction.setBlockHash(transaction.serialized(), changedBlockhash);
      assertArrayEquals(
          changedBlockhash,
          TransactionSkeleton.deserializeSkeleton(transaction.serialized()).blockHash()
      );
    }

    final var rejectedSkeleton = skeletonForMessage(rejected.message());
    for (final var multipleTables : List.of(false, true)) {
      final var transaction = assertDoesNotThrow(
          () -> canonicalVersionedTransaction(rejected, rejectedSkeleton, multipleTables),
          "Sava permits constructing bytes that the RPC will reject"
      );
      transaction.setRecentBlockHash(rejected.blockhash());
      assertEquals((byte) 0x80, transaction.serialized()[0]);
      assertArrayEquals(rejected.message(), messageBytes(transaction));
    }

    final var signer = Signer.createFromPrivateKey(rejected.signerSeeds().getFirst());
    final byte[] output = new byte[
        1 + (128 * Transaction.SIGNATURE_LENGTH) + rejected.message().length
    ];
    final int messageOffset = 1 + (128 * Transaction.SIGNATURE_LENGTH);
    System.arraycopy(rejected.message(), 0, output, messageOffset, rejected.message().length);
    // A buffer assembled by hand declares its own signature count, exactly as every createTx path
    // does at allocation. The helper reads that byte rather than overwriting it, so that a count
    // disagreeing with the caller cannot relocate the message and write a signature over it.
    output[0] = (byte) 128;
    assertDoesNotThrow(
        () -> Transaction.sign(java.util.Collections.nCopies(128, signer), output),
        "the static signing helper retains its permissive byte-oriented contract"
    );
    assertEquals((byte) 0x80, output[0]);
    assertArrayEquals(rejected.message(), Arrays.copyOfRange(output, messageOffset, output.length));  }

  @Test
  void accountAndHeaderUnsignedByteBoundariesRemainPermissiveForAnalysis() throws IOException {
    final var maxIndex = loadFixture().vectors().stream()
        .filter(vector -> vector.id().equals("max_account_index_255"))
        .findFirst()
        .orElseThrow();
    final var maxIndexTx = Transaction.createTx(
        maxIndex.feePayer(),
        maxIndex.instructions().stream().map(IxSpec::toInstruction).toList()
    );
    assertEquals(256, TransactionSkeleton.deserializeSkeleton(maxIndexTx.serialized()).numIncludedAccounts());

    final var tooManyAccounts = Instruction.createInstruction(
        key(0x7fff),
        metas(255, false, false, 0x1000),
        new byte[]{1}
    );
    final var totalOverflow = assertDoesNotThrow(
        () -> Transaction.createTx(key(0x7ffe), tooManyAccounts),
        "RPC-invalid account indices remain constructible"
    );
    assertEquals(257, TransactionSkeleton.deserializeSkeleton(totalOverflow.serialized()).numIncludedAccounts());

    final var readonlyHeaderOverflow = assertDoesNotThrow(
        () -> Transaction.createTx(Instruction.createInstruction(
            key(0x6fff),
            metas(255, false, false, 0x2000),
            new byte[]{2}
        )),
        "header counts continue to narrow to their wire byte"
    );
    final var readonlyOverflowSkeleton = TransactionSkeleton.deserializeSkeleton(readonlyHeaderOverflow.serialized());
    assertEquals(256, readonlyOverflowSkeleton.numIncludedAccounts());
    assertEquals(0, readonlyOverflowSkeleton.numReadonlyUnsignedAccounts());

    final var emptyTable = emptyLookupTable(0x7100);
    final var secondEmptyTable = emptyLookupTable(0x7101);
    final var sortedTooManyAccounts = TransactionRecord.sortV0Accounts(merge(
        AccountMeta.createFeePayer(key(0x70ff)),
        tooManyAccounts
    ));
    final var totalOverflowInstruction = Instruction.createInstruction(
        key(0x7ffd),
        metas(256, false, false, 0x3000),
        new byte[]{3}
    );
    final var totalOverflowAccounts = TransactionRecord.sortV0Accounts(merge(
        AccountMeta.createFeePayer(key(0x70fe)),
        totalOverflowInstruction
    ));
    for (final var multipleTables : List.of(false, true)) {
      final var v0ReadonlyHeaderOverflow = assertDoesNotThrow(
          () -> createVersioned(
              List.of(tooManyAccounts),
              tooManyAccounts.serializedLength(),
              sortedTooManyAccounts,
              emptyTable,
              secondEmptyTable,
              multipleTables
          ),
          "v0 header overflow remains constructible"
      );
      assertEquals(257, TransactionSkeleton.deserializeSkeleton(v0ReadonlyHeaderOverflow.serialized()).numIncludedAccounts());

      final var totalAccountOverflow = assertDoesNotThrow(
          () -> createVersioned(
              List.of(totalOverflowInstruction),
              1 + CompactU16Encoding.getByteLen(256) + 256 + 1 + 1,
              totalOverflowAccounts,
              emptyTable,
              secondEmptyTable,
              multipleTables
          ),
          "v0 account-index overflow remains constructible"
      );
      assertEquals(258, TransactionSkeleton.deserializeSkeleton(totalAccountOverflow.serialized()).numIncludedAccounts());
    }
  }

