/// First-party defensive conformance for Sava's SIMD-0385 transaction v1 reader. The committed
/// fixture is generated by a locked Rust crate driving `solana-message` 4.5.0's `v1` module and
/// `solana-transaction` 4.2.0's `VersionedTransaction`, at the same pinned `solana-sdk` commit the
/// sibling legacy fixture uses; normal Java tests need neither Rust nor network access.
///
/// Every offset, length, mask value, header, signature, and error in the fixture is produced by
/// executing Rust rather than by Sava, so this is the external oracle for the v1 wire format:
/// a self-consistent off-by-one in a Sava constant fails here instead of hiding behind Sava's own
/// round trip. Address lookup semantics, the legacy and v0 message formats, and runtime
/// compute-budget behaviour are outside this fixture.
///
/// Where Sava is deliberately more permissive than Rust's `v1::Message::validate` — it is a
/// byte-oriented builder and analyzer that leaves submission validation to the RPC — the current
/// behaviour is pinned rather than forced to reject, and the divergence is called out at the
/// assertion. See [#v1PopulationLimitsAreReportedRatherThanRejected] and
/// [#v1OutOfRangeInstructionAccountIndexIsRejected].
///
/// That permissiveness stops where a message would parse into a plausible-looking WRONG view rather
/// than an invalid-but-faithful one — see [#v1UnknownConfigMaskBitsAreRejectedAsRustRejectsThem],
/// which is the same line the two header rules draw.
