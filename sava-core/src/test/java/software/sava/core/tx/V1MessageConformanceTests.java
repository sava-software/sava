  private record Vector(
      String id,
      String category,
      int numRequiredSignatures,
      int numReadonlySigned,
      int numReadonlyUnsigned,
      long configMask,
      int numAddresses,
      int numInstructions,
      int messageLen,
      Map<String, Integer> offsets,
      Map<String, ConfigValue> configValues,
      byte[] message,
      List<byte[]> addresses,
      List<IxSpec> instructions,
      List<byte[]> signerSeeds,
      List<byte[]> signatures,
      int signatureBlockOffset,
      byte[] transaction,
      boolean rustValidate,
      boolean rustDeserialize,
      boolean rustDeserializeWithPrefix,
      boolean rustWireRoundTrip,
      String rustValidateError,
      String rustDeserializeError
  ) {

    /// The v1 transaction wire: the serialized message, then the signature block, with nothing
    /// between them. Unsigned vectors carry all-zero placeholder slots.
    byte[] wire() {
      final byte[] wire = new byte[messageLen + (signatures.size() * Transaction.SIGNATURE_LENGTH)];
      System.arraycopy(message, 0, wire, 0, message.length);
      int offset = messageLen;
      for (final var signature : signatures) {
        System.arraycopy(signature, 0, wire, offset, Transaction.SIGNATURE_LENGTH);
        offset += Transaction.SIGNATURE_LENGTH;
      }
      return wire;
    }
  }

